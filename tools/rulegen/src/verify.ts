import { isIP } from "node:net";
import { ipNumber, RuleValidationError, validateRuleSet, type Rule, type RuleSet } from "./model.ts";

export type ArtifactTarget = "loon" | "quantumultx" | "sing-box";

function fail(location: string, reason: string): never {
  throw new RuleValidationError(`${location}: ${reason}`);
}

function checked(rules: Rule[], location: string): Rule[] {
  // Reuse input validity constraints, not the renderer's client-keyword mapping.
  // Metadata here is synthetic; neither source metadata nor child output is logged.
  try {
    validateRuleSet({
      version: 1,
      metadata: { name: "Static verification", author: "ProxyKit", updated: "2026-01-01", source: "Local artifact", note: "Generated subset only" },
      groups: [{ name: "Parsed predicates", rules }],
    });
  } catch (error) {
    if (error instanceof RuleValidationError) fail(location, error.message);
    fail(location, "invalid predicate data");
  }
  return rules;
}

/** Static parser for ProxyKit's generated subset, not a Loon/QX client loader. */
export function parseListArtifact(text: string, target: "loon" | "quantumultx", compatibility?: RuleSet["compatibility"]): Rule[] {
  const rules: Rule[] = [];
  for (const [index, original] of text.split(/\r?\n/).entries()) {
    const location = `${target}.line[${index + 1}]`;
    const line = original.trim();
    if (!line) continue;
    // Comments can legitimately look like rules. Treat every comment as inert,
    // including disabled candidates; byte fidelity is proved by the existing check command.
    if (line.startsWith("#")) continue;
    const fields = line.split(",");
    if (fields.some(field => !field || field.trim() !== field) || fields.length < 2 || fields.length > 3) {
      fail(location, "expected a canonical two-field rule or supported third field");
    }
    const [keyword, value, third] = fields;
    let type: Rule["type"];
    // This table deliberately lives outside generate.ts; tests assert actual output semantics.
    switch (keyword) {
      case "DOMAIN": if (target !== "loon") fail(location, "unsupported rule type"); type = "domain"; break;
      case "DOMAIN-SUFFIX": if (target !== "loon") fail(location, "unsupported rule type"); type = "domain-suffix"; break;
      case "HOST": if (target !== "quantumultx") fail(location, "unsupported rule type"); type = "domain"; break;
      case "HOST-SUFFIX": if (target !== "quantumultx") fail(location, "unsupported rule type"); type = "domain-suffix"; break;
      case "IP-CIDR": type = "ipv4-cidr"; break;
      case "IP-CIDR6": if (target !== "loon") fail(location, "unsupported rule type"); type = "ipv6-cidr"; break;
      case "IP6-CIDR": if (target !== "quantumultx") fail(location, "unsupported rule type"); type = "ipv6-cidr"; break;
      default: fail(location, "unsupported rule type");
    }
    if (third !== undefined && (!type.endsWith("-cidr") || third !== "no-resolve")) fail(location, "unsupported third field");
    if (target === "quantumultx" && third && compatibility?.quantumultx_no_resolve !== "legacy-policy-token") {
      fail(location, "legacy policy token requires explicit compatibility and filter_remote force-policy");
    }
    const rule: Rule = { type, value };
    // In QX this records the historical text for fidelity, not a DNS control flag.
    if (third) rule.options = { no_resolve: true };
    rules.push(rule);
  }
  return checked(rules, target);
}

/** Only accepts version 2 and the one-predicate-per-rule subset generated by ProxyKit. */
export function parseSingBoxArtifact(text: string): Rule[] {
  let root: any;
  try { root = JSON.parse(text); } catch { fail("sing-box", "invalid source JSON"); }
  if (!root || typeof root !== "object" || Array.isArray(root) || Object.keys(root).sort().join(",") !== "rules,version" || root.version !== 2 || !Array.isArray(root.rules)) {
    fail("sing-box", "expected generated source version 2");
  }
  const rules: Rule[] = root.rules.map((entry: unknown, index: number) => {
    const location = `sing-box.rules[${index}]`;
    if (!entry || typeof entry !== "object" || Array.isArray(entry) || Object.keys(entry).length !== 1) fail(location, "expected one predicate");
    const [field, values] = Object.entries(entry)[0];
    if (!Array.isArray(values) || values.length !== 1 || typeof values[0] !== "string") fail(location, "expected one string matcher");
    let type: Rule["type"];
    if (field === "domain") type = "domain";
    else if (field === "domain_suffix") type = "domain-suffix";
    else if (field === "ip_cidr") type = values[0].includes(":") ? "ipv6-cidr" : "ipv4-cidr";
    else fail(location, "unsupported predicate");
    return { type, value: values[0] };
  });
  return checked(rules, "sing-box");
}

/** Compare ordered active predicates with the source; check handles comments/candidate fidelity. */
export function verifyArtifact(text: string, target: ArtifactTarget, expected: RuleSet): { total: number; enabled: number } {
  const actual = target === "sing-box" ? parseSingBoxArtifact(text) : parseListArtifact(text, target, expected.compatibility);
  const source = expected.groups.flatMap(group => group.rules).filter(rule => rule.enabled !== false);
  if (actual.length !== source.length) fail(target, "predicate count differs from source");
  actual.forEach((rule, index) => {
    const wanted = source[index];
    if (rule.type !== wanted.type || rule.value !== wanted.value || (rule.enabled !== false) !== (wanted.enabled !== false) ||
      (target !== "sing-box" && !!rule.options?.no_resolve !== !!wanted.options?.no_resolve)) {
      fail(`${target}.rules[${index}]`, "ordered predicate, state or options differ from source");
    }
  });
  return { total: actual.length, enabled: actual.filter(rule => rule.enabled !== false).length };
}

/** Target membership only: no DNS, routing policy, traffic generation or global configuration. */
export function matchesRules(rules: readonly Rule[], probe: string): boolean {
  if (probe.includes("%")) fail("probe", "scoped IP probes are not supported");
  const family = isIP(probe);
  if (!family) checked([{ type: "domain", value: probe }], "probe");
  return rules.some(rule => {
    if (rule.enabled === false) return false;
    if (rule.type === "domain") return !family && rule.value === probe;
    if (rule.type === "domain-suffix") return !family && (probe === rule.value || probe.endsWith(`.${rule.value}`));
    if (family !== (rule.type === "ipv4-cidr" ? 4 : 6)) return false;
    const [address, prefix] = rule.value.split("/");
    const shift = BigInt((family === 4 ? 32 : 128) - Number(prefix));
    return ipNumber(probe) >> shift === ipNumber(address) >> shift;
  });
}

/** Checks the documented project filter_remote example subset; never fetches its URL. */
export function verifyQxRemoteEntry(line: string): { policyOverridden: true } {
  const location = "quantumultx.filter_remote";
  if (/[\x00-\x1f\x7f\u2028\u2029]/.test(line)) fail(location, "expected one entry line");
  const [address, ...fields] = line.split(",").map(part => part.trim());
  let url: URL;
  try { url = new URL(address); } catch { fail(location, "expected HTTPS remote URL"); }
  if (url.protocol !== "https:" || !url.hostname || url.username || url.password) fail(location, "expected HTTPS remote URL without credentials");
  const parsed = new Map<string, string>();
  for (const [index, field] of fields.entries()) {
    const equals = field.indexOf("=");
    const key = field.slice(0, equals).trim();
    const value = field.slice(equals + 1).trim();
    if (equals < 1 || !["tag", "force-policy", "enabled"].includes(key) || !value || parsed.has(key)) {
      fail(`${location}.fields[${index}]`, "unknown, empty or duplicate field");
    }
    parsed.set(key, value);
  }
  if (!parsed.has("tag") || !parsed.has("force-policy") || parsed.get("enabled") !== "true") {
    fail(location, "require nonempty tag, force-policy and enabled=true");
  }
  return { policyOverridden: true };
}
